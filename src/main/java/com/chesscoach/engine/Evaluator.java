    /** Оценка с точки зрения стороны, которая сейчас ходит. */
    static int evaluate(Board board) {
        int nonPawnMaterial = 0;
        for (int s = 0; s < 64; s++) {
            int abs = Math.abs(board.pieceAt(s));
            if (abs >= Board.KNIGHT && abs <= Board.QUEEN) nonPawnMaterial += VALUES[abs];
        }
        boolean endgame = nonPawnMaterial <= 2600;

        int score = 0;
        for (int s = 0; s < 64; s++) {
            int piece = board.pieceAt(s);
            if (piece == Board.EMPTY) continue;
            int abs = Math.abs(piece);
            // В таблицах индекс 0 — это a8, поэтому для белых горизонталь зеркалится.
            int index = piece > 0 ? s ^ 56 : s;
            int value = VALUES[abs] + table(abs, endgame)[index];
            score += piece > 0 ? value : -value;
        }
        return board.isWhiteToMove() ? score : -score;
    }

    private static int[] table(int abs, boolean endgame) {
        return switch (abs) {
            case Board.PAWN -> PAWN_TABLE;
            case Board.KNIGHT -> KNIGHT_TABLE;
            case Board.BISHOP -> BISHOP_TABLE;
            case Board.ROOK -> ROOK_TABLE;
            case Board.QUEEN -> QUEEN_TABLE;
            default -> endgame ? KING_END_TABLE : KING_MIDDLE_TABLE;
        };
    }
